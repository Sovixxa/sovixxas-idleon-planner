 await page.locator('#trueDrOrb').fill('0');
 await page.locator('#trueDrSearch').fill('');
 await page.locator('#trueDrMonster').selectOption('all');
 await page.waitForFunction(()=>[...document.querySelectorAll('#trueDrRows img')].every(i=>i.complete&&i.naturalWidth>0));
 await page.screenshot({path:'../audit/true-dr-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+1));
