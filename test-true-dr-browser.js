 assert.match(await page.locator('#trueDrRows').innerText(),/1 in/);
 await page.locator('#trueDrCharacter').selectOption({index:1});
 assert.match(await page.locator('#trueDrRows .true-dr-quantity').last().innerText(),/≈ [\d,]+/);
 console.log('Imported Green Mushroom quantity:',await page.locator('#trueDrRows .true-dr-quantity').last().innerText());
 await page.locator('#quickNotesToggle').click();
 await page.waitForFunction(()=>[...document.querySelectorAll('#trueDrRows img')].every(i=>i.complete&&i.naturalWidth>0));
