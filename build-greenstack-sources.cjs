const fs=require('fs'),path=require('path');
const base=path.join(__dirname,'vendor/idleon-toolbox/data/website-data');
const read=n=>JSON.parse(fs.readFileSync(path.join(base,n+'.json'),'utf8'));
const items=read('items'),shared=read('shared-data'),drops=read('monsterDrops'),crafts=read('crafts');
const records={};const clean=s=>String(s||'').replaceAll('_',' ');
function add(id,text){
 const world=String(text).match(/(?:Chest.*?\(W|Colosseum.*?\(W)([1-7])\)/i);
 if(world)text='W'+world[1]+' Colo';
 if(text&&!/^DropTable/i.test(text))(records[id]||=[]).push(clean(text));}
// Supplement current catalogs with the local item-reference acquisition labels.
const reference=path.join(__dirname,'../.tmp-idleon-efficiency/data/domain/data/ItemRepo.ts');
if(fs.existsSync(reference)){
 const source=fs.readFileSync(reference,'utf8');
 for(const part of source.split('new ItemBase(').slice(1)){
  const id=part.match(/^"([^"]+)"/)?.[1];if(!id)continue;
  for(const match of part.split('"recipeFrom"')[0].matchAll(/"txtName":\s*("(?:[^"\\]|\\.)*")/g))add(id,JSON.parse(match[1]));
 }
}
for(const shop of Object.values(shared.shops))for(const item of shop.items||[])add(item.rawName,'Shop: '+clean(shop.name));
for(const recipe of Object.values(crafts))add(recipe.rawName,'Craft at the Anvil: '+recipe.materials.map(m=>m.itemQuantity+' '+clean(m.itemName)).join(', '));
for(const item of Object.values(shared.anvilProducts))add(item.rawName,'Anvil production (Smithing level '+item.levelReq+')');
for(const rows of Object.values(drops))for(const drop of rows){
 const locations=shared.mapEnemiesArray.flatMap((id,i)=>id===drop.monsterRawName&&shared.mapNames[i]?[clean(shared.mapNames[i])]:[]);
 add(drop.rawName,'Drop: '+clean(drop.monsterDisplayName||drop.monsterRawName)+(locations.length?' — '+locations.join(', '):'')+(drop.questLink&&drop.questLink!=='N/A'?' (quest: '+clean(drop.questLink)+')':''));
}
for(const [id,item] of Object.entries(items))if(item.typeGen==='bBar')add(id,'Smelt ores in the Forge');
for(const [id,sources] of Object.entries(require('./greenstack-source-supplements.json').records))for(const source of sources)add(id,source);
for(const [npc,quests] of Object.entries(read('quests')))for(const quest of Object.values(quests))for(const reward of quest.rewards||[])add(reward.rawName,'Quest: '+clean(npc)+' — '+clean(quest.Name||quest.QuestName));
for(const awards of Object.values(shared.itemSources.bundles||{}))for(const id of Object.keys(awards))add(id,'Gem Shop bundle reward (offer availability varies)');
for(const [system,label] of Object.entries({dungeon:'Party Dungeons',royalGuardian:'Royal Guardian',trashIsland:'Trash Island'}))for(const id of Object.keys(shared.itemSources[system]||{}))add(id,label);
for(const category of read('gemShop'))for(const offers of Object.values(category.sections||{}))for(const offer of offers)if(items[offer.rawName]&&offer.rawName!=='Blank')add(offer.rawName,'Gem Shop — '+clean(category.name)+' (offer availability varies)');
const vm=require('vm'),hatContext={window:{}};vm.runInNewContext(fs.readFileSync(path.join(__dirname,'hat-sources-data.js'),'utf8'),hatContext);
for(const [id,entry] of Object.entries(hatContext.window.HAT_SOURCES.records))for(const route of entry.routes)add(id,route.kind+': '+route.title+(route.note?' — '+route.note:''));
// Dynamic reward handlers are outside the ordinary monster-drop catalog.
// Verified against audit/N.js boss reward assembly and seasonal event handlers.
const special={
 Crystal3:['Defeat Chizoar — World 3 boss reward'],
 Crystal4:['Defeat Massive Troll — World 4 boss reward'],
 Crystal5:['Defeat Kattlekruk — World 5 boss reward'],
 Crystal6:['Defeat Emperor — World 6 boss reward'],
 Quest112:['Seasonal event box rewards, including Goldrush Edible Coins'],
 Quest76:['Seasonal event box rewards, including Goldrush Edible Coins'],
 Quest101:['Arcane Cultist AFK gains after unlocking Arcane Rock collection with Aether Fragments'],
 Quest111:['Monster kills during the seasonal event (one carried Lucky Candle at a time)'],
 Quest114:['Monster kills during the seasonal event (one carried Glimmerwick Candle at a time)'],
 Quest119:['Monster kills while the Pet Bonus Token promotion is enabled'],
 Quest120:['Buried Treasure event minigame rewards (seasonal availability)'],
 KeyFrag:['Party Dungeons — dungeon reward drops'],
 EquipmentTools13:['Random event: Snake Swarm'],
 CaveGoldPiece:['The Caverns — Bravery monument rewards']
};
for(const [id,sources] of Object.entries(special))for(const source of sources)add(id,source);
const {normalizeSources}=require('./greenstack-source-normalize.cjs');
for(const id of Object.keys(records))records[id]=normalizeSources(records[id]);
fs.writeFileSync(path.join(__dirname,'greenstack-sources.js'),'// Generated by build-greenstack-sources.cjs from local acquisition catalogs.\nwindow.GREENSTACK_SOURCES='+JSON.stringify(records)+';\n');
console.log('Generated sources for '+Object.keys(records).length+' items');
