'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const box={console};vm.createContext(box);vm.runInContext(fs.readFileSync('prayer-math-engine.js','utf8'),box);
const optimize=box.PrayerMath.getOptimizedLandRankUpgrades;
const ranks=Array.from({length:20},(_,i)=>({name:'Upgrade '+i,base:10,upgradeLevel:0,unlockAt:0}));
const account={farming:{ranks,rankMulti:1,totalPoints:100,availablePoints:10,fifthColumnMaxLevel:2,plot:[{rank:10,seedType:0}]}};
let plan=optimize(account,100,{onlyAffordable:true,weights:{farmingExp:1}});
assert.equal(plan.length,10);assert(plan.every(x=>[5,12,16].includes(x.index)));
assert.equal(ranks.reduce((sum,r)=>sum+r.upgradeLevel,0),0,'planning must not mutate save');
plan=optimize(account,10,{onlyAffordable:true,weights:{farmingExp:1},excluded:[5,12]});
assert(plan.every(x=>x.index===16));
assert.equal(optimize(account,10,{weights:{farmingExp:0}}).length,0);
assert.equal(optimize(account,10,{weights:{farmingExp:1},excluded:[5,12,16]}).length,0);
plan=optimize(account,100,{onlyAffordable:true,weights:{character:1}});
assert.equal(plan.length,8);assert(plan.every(x=>x.newLevel<=2));
ranks[16].unlockAt=101;
assert.equal(optimize(account,10,{weights:{farmingExp:1},excluded:[5,12]}).length,0);
const a=optimize(account,1,{weights:{farmingExp:100,overgrowth:1}}),b=optimize(account,1,{weights:{farmingExp:1,overgrowth:100}});
assert([5,12].includes(a[0].index));assert([7,11,18].includes(b[0].index));
console.log('Land rank optimizer: budget, priorities, exclusions, unlocks, caps and immutable save pass.');
