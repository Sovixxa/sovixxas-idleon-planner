'use strict';
const fs=require('node:fs'),vm=require('node:vm'),assert=require('node:assert/strict');
const S=require('./afk-save-model');
vm.runInThisContext(fs.readFileSync('prayer-math-engine.js','utf8'));
const M={...PrayerMath,mapNames:{323:PrayerMath.mapNames[323]}};
const raw=JSON.parse(fs.readFileSync('../example json.txt','utf8')),before=JSON.stringify(raw);
const options={skill:0,boostFoods:true,foods:{0:{0:'FoodPotYe5'}},statueWeek:true};
const prepared=S.prepare(raw,M,options);
assert.equal(prepared.copy.serverVars.voteCat2[0],26);
assert.equal(prepared.data.EquipOrder_0[2][0],'FoodPotYe5');
assert.equal(prepared.data.EquipQTY_0[2][0],1);
assert.equal(JSON.stringify(raw),before);
assert.throws(()=>S.prepare(raw,M,{...options,skill:3}),/Invalid boost food/);
const stale=structuredClone(raw);stale.data.FoodSlO_0=2;
stale.data.EquipOrder_0=typeof stale.data.EquipOrder_0==='string'?JSON.parse(stale.data.EquipOrder_0):stale.data.EquipOrder_0;
stale.data.EquipQTY_0=typeof stale.data.EquipQTY_0==='string'?JSON.parse(stale.data.EquipQTY_0):stale.data.EquipQTY_0;
stale.data.EquipOrder_0[2][0]='FoodPotYe5';stale.data.EquipQTY_0[2][0]=0;
stale.data.EquipOrder_0[2][3]='FoodPotYe5';stale.data.EquipQTY_0[2][3]=100;
const clean=S.prepare(stale,M,{activeBuffs:false,prayers:false});
assert.equal(clean.data.EquipOrder_0[2][0],'Blank');assert.equal(clean.data.EquipOrder_0[2][3],'Blank');
assert.deepEqual(clean.data.BuffsActive_0,[]);assert.deepEqual(clean.data.Prayers_0,[]);
const week=structuredClone(raw);week.serverVars.voteCat2=[26,1,2,3];
assert.equal(S.prepare(week,M,{statueWeek:false}).copy.serverVars.voteCat2[0],-1);
assert.equal(S.prepare(raw,M,{statueWeek:false}).copy.serverVars.voteCat2[0],raw.serverVars.voteCat2[0]);
const base=S.calculate(raw,M),food=S.calculate(raw,M,{...options,statueWeek:false}),statues=S.calculate(raw,M,{statueWeek:true});
const node=r=>r[0][0].nodes.find(n=>n.map===323);
assert(node(base).rate>0);assert.notEqual(node(food).combat.expMultiplier,node(base).combat.expMultiplier);
assert(food[0][0].loadout.food.some(n=>/EXP|Experience/i.test(n)));
assert.notEqual(node(statues).rate,node(base).rate,'Statue Week must rebuild the account and character stats');
for(const skill of [0,1,3,4,6])assert(base[0][skill].foodChoices.length>0);
assert(base[0][1].foodChoices.every(f=>S.foodEffects[1].includes(f.effect)));
assert.equal(JSON.stringify(raw),before);
console.log('AFK scenarios: Statue Week, food substitution, skill filtering, empty/locked food slots, prayer/buff removal and save immutability passed.');
