'use strict';
const assert=require('node:assert/strict');
const q=require('./planner-qol');
const now=new Date(2026,8,23,10).getTime(),settings={resetHour:8,resetDay:1};
assert.equal(q.isDone({repeat:'daily',done:new Date(2026,8,23,7).getTime()},now,settings),false);
assert.equal(q.isDone({repeat:'daily',done:new Date(2026,8,23,9).getTime()},now,settings),true);
assert.equal(q.isDone({repeat:'weekly',done:new Date(2026,8,20,9).getTime()},now,settings),false);
assert.equal(q.isDone({repeat:'weekly',done:new Date(2026,8,21,9).getTime()},now,settings),true);
assert.equal(q.isDone({repeat:'once',done:1},now,settings),true);
assert.equal(q.isDone({repeat:'daily',done:null},now,settings),false);
