const first=q.snapshot(raw,{vials:[{name:'Vial',level:'Lv 0',status:'missing'},{name:'Other',level:'Lv 12',status:'active'}]},now);
const next=q.snapshot({...raw,data:{...raw.data,Lv0_0:[101]}},{vials:[{name:'Vial',level:'Lv 1',status:'active'},{name:'Other',level:'Lv 13 · MAX',status:'active'}]},now+1000);
assert.equal(first.savedAt,now-3600000);assert.deepEqual(q.compare(first,next).map(c=>c.kind),['Unlocked','Completed','Level gained']);
assert.equal(q.compare(first,{...next,account:'Bob'}).length,0);assert.equal(q.compare(next,next).length,0);
assert.equal(q.snapshot({data:{}},{},now).savedAt,null);
assert.throws(()=>q.validate({goals:[{name:'bad'}]}));assert.throws(()=>q.validate(JSON.parse('{"notes":{"__proto__":"bad"}}')));
assert.throws(()=>q.validate({pages:{cards:{invalid:{}}}}));assert.throws(()=>q.validate({tasks:[{id:'a',name:'A',repeat:'daily',done:'yesterday'}]}));
