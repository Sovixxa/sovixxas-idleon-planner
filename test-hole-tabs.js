'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const source=fs.readFileSync('app.js','utf8');
const remaining=fs.readFileSync('remaining-worlds.js','utf8');
const groups=source.match(/const HOLE_TAB_GROUPS=\[([\s\S]*?)\n  \];/)?.[1]||'';
for(const key of ['hole','holeSchematics','holeMajik','holeMeasurements','holeStudies'])assert.match(groups,new RegExp(`['"]${key}['"]`));
for(const key of ['holeFloors','holeBravery','holeJustice','holeWisdom','holeSanctum','holeBell','holeWell','holeFountain','holeResources','holeHarp','holeLamp','holeDawgDen','holeJars','holeGambit','holeCove'])assert.match(groups,new RegExp(`['"]${key}['"]`));
assert.doesNotMatch(groups,/['"]holeTrench['"]/);
assert.match(source,/className='hole-tab-stack'/);
assert.match(source,/data-hole-group/);
assert.match(source,/HOLE_VILLAGER_ICONS=\{hole:0,holeSchematics:1,holeMajik:2,holeMeasurements:3,holeStudies:4\}/);
assert.doesNotMatch(remaining,/Discovered buildings/);
assert.match(remaining,/id="explorerDetail"/);
assert.match(remaining,/Explorer progress reveals new caverns/);
assert.match(remaining,/HoleGshape/);
assert.match(remaining,/order=\[0,2,4,6,8,10,1,3,5,7,9,11\]/);
assert.match(remaining,/Gooey Upgrades/);
assert.match(remaining,/Quartz Upgrades/);
assert.match(remaining,/const floorInfo=\[/);
assert.match(remaining,/Crystal Glunko Cove/);
const bonusSystems=fs.readFileSync('bonus-systems.js','utf8');
assert.match(bonusSystems,/data-hole-bonus/);
assert.match(bonusSystems,/id="holeBonusDetail"/);
console.log('Hole tabs: five pictured villagers and all cavern systems are grouped correctly');
